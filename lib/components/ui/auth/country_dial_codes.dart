import 'package:flutter/foundation.dart';

/// Country descriptor for phone authentication dial code selection.
@immutable
class CountryDialCode {
  final String name;
  final String dialCode;
  final String isoCode;

  const CountryDialCode({
    required this.name,
    required this.dialCode,
    required this.isoCode,
  });

  /// Computed Unicode flag emoji for the country ISO code.
  String get flagEmoji {
    if (isoCode.length != 2) return '🌐';
    final upper = isoCode.toUpperCase();
    final first = 0x1F1E6 + (upper.codeUnitAt(0) - 0x41);
    final second = 0x1F1E6 + (upper.codeUnitAt(1) - 0x41);
    return String.fromCharCode(first) + String.fromCharCode(second);
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is CountryDialCode &&
          runtimeType == other.runtimeType &&
          isoCode == other.isoCode &&
          dialCode == other.dialCode;

  @override
  int get hashCode => Object.hash(isoCode, dialCode);

  @override
  String toString() => '$name ($dialCode, $isoCode)';
}

