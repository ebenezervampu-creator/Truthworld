mixin AdvertiserLanguagesMixin {
  final List<Map<String, String>> supportedLanguages = advertiserSupportedLanguages;
  final List<Map<String, String>> supportedAudioLanguages = advertiserSupportedAudioLanguages;

  String getLanguageName(String code) {
    final found = supportedAudioLanguages.firstWhereOrNull((l) => l['code'] == code) ??
        supportedLanguages.firstWhereOrNull((l) => l['code'] == code);
    return found?['name'] ?? code.toUpperCase();
  }
}
