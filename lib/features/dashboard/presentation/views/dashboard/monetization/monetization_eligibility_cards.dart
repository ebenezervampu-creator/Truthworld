/// Partner eligibility section showing unlocked subscriber gate, channel gate, cash out gate, and AI features.
class PartnerEligibilitySection extends StatelessWidget {
  const PartnerEligibilitySection({
    required this.isCustom,
    this.isChannelMonetized = true,
    super.key,
  });

  final bool isCustom;
  final bool isChannelMonetized;

  @override
  Widget build(BuildContext context) {
    return MonetizationCardContainer(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const MonetizationSectionTitle(title: 'Partner Eligibility Status'),
          const SizedBox(height: 16),
          LayoutBuilder(
            builder: (context, constraints) {
              final isWide = constraints.maxWidth >= 600;
              final tiles = [
                const EligibilityStatusTile(
                  icon: Icons.people_outline_rounded,
                  title: 'Subscriber Gate',
                  value: '0 Required',
                  subtitle: 'No Sub Count Barrier',
                  isUnlocked: true,
                ),
                EligibilityStatusTile(
                  icon: Icons.verified_user_outlined,
                  title: 'Channel Gate',
                  value: '1k Views, 30h & KYC',
                  subtitle: isChannelMonetized
                      ? 'Monetization Active'
                      : 'Any Video + KYC Required',
                  isUnlocked: isChannelMonetized,
                ),
                const EligibilityStatusTile(
                  icon: Icons.timer_outlined,
                  title: 'Cash Out Gate',
                  value: '1k Views & 30h',
                  subtitle: 'Per video for cash withdrawal',
                  isUnlocked: true,
                ),
                const EligibilityStatusTile(
                  icon: Icons.auto_awesome_rounded,
                  title: 'AI Features',
                  value: 'Instant Use',
                  subtitle: 'Subtitles & Dubbing',
                  isUnlocked: true,
                ),
              ];

              if (isWide) {
                return Row(
                  children: [
                    for (int i = 0; i < tiles.length; i++) ...[
                      if (i > 0) const SizedBox(width: 10),
                      Expanded(child: tiles[i]),
                    ],
                  ],
                );
              }

              final itemWidth = (constraints.maxWidth - 10) / 2;
              return Wrap(
                spacing: 10,
                runSpacing: 10,
                children: tiles
                    .map((t) => SizedBox(width: itemWidth, child: t))
                    .toList(),
              );
            },
          ),
        ],
      ),
    );
  }
}

/// Reusable status tile within the partner eligibility section in clean monochrome.
class EligibilityStatusTile extends StatelessWidget {
  const EligibilityStatusTile({
    required this.icon,
    required this.title,
    required this.value,
    required this.subtitle,
    required this.isUnlocked,
    super.key,
  });

  final IconData icon;
  final String title;
  final String value;
  final String subtitle;
  final bool isUnlocked;

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: AppColors.bgPage,
        borderRadius: BorderRadius.circular(12),
        border: Border.all(color: AppColors.bgDivider),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Icon(
                icon,
                color: Colors.white,
                size: 20,
              ),
              const Spacer(),
              Icon(
                isUnlocked ? Icons.check_circle_rounded : Icons.hourglass_top_rounded,
                color: isUnlocked ? Colors.white : AppColors.textSecondary,
                size: 16,
              ),
            ],
          ),
          const SizedBox(height: 10),
          Text(
            title,
            style: const TextStyle(
              fontSize: 12,
              color: AppColors.textSecondary,
              fontWeight: FontWeight.w500,
            ),
          ),
          const SizedBox(height: 2),
          Text(
            value,
            style: const TextStyle(
              fontSize: 14,
              fontWeight: FontWeight.bold,
              color: AppColors.textPrimary,
            ),
          ),
          const SizedBox(height: 2),
          Text(
            subtitle,
            maxLines: 1,
            overflow: TextOverflow.ellipsis,
            style: const TextStyle(
              fontSize: 10,
              color: AppColors.textSecondary,
            ),
          ),
        ],
      ),
    );
  }
}
