class TranscriptSegment {

  TranscriptSegment({
    required this.startTime,
    required this.endTime,
    required this.text,
    this.language,
  });

  factory TranscriptSegment.fromMap(Map<String, dynamic> map) {
    return TranscriptSegment(
      startTime: (map['startTime'] ?? 0).toDouble(),
      endTime: (map['endTime'] ?? 0).toDouble(),
      text: map['text'] ?? '',
      language: map['language'],
    );
  }
  final double startTime; // in seconds
  final double endTime; // in seconds
  final String text;
  final String? language;

  Map<String, dynamic> toMap() {
    return {
      'startTime': startTime,
      'endTime': endTime,
      'text': text,
      'language': language,
    };
  }
}

class VideoTranscript {

  VideoTranscript({
    required this.videoId,
    required this.language,
    required this.segments,
    required this.createdAt, this.isAutoGenerated = false,
  });

  factory VideoTranscript.fromMap(Map<String, dynamic> map, [String? docId]) {
    return VideoTranscript(
      videoId: map['videoId'] ?? docId ?? '',
      language: map['language'] ?? 'en',
      segments: (map['segments'] as List? ?? [])
          .map((s) => TranscriptSegment.fromMap(Map<String, dynamic>.from(s)))
          .toList(),
      isAutoGenerated: map['isAutoGenerated'] ?? false,
      createdAt: map['createdAt'] != null
          ? DateTime.parse(map['createdAt'])
          : DateTime.now(),
    );
  }

  factory VideoTranscript.empty() {
    return VideoTranscript(
      videoId: '',
      language: 'en',
      segments: [],
      createdAt: DateTime.now(),
    );
  }
  final String videoId;
  final String language;
  final List<TranscriptSegment> segments;
  final bool isAutoGenerated;
  final DateTime createdAt;

  /// Get full transcript text
  String get fullText => segments.map((s) => s.text).join(' ');

  /// Get transcript segments for a specific time range (in seconds)
  List<TranscriptSegment> getSegmentsInTimeRange(
    double startTime,
    double endTime,
  ) {
    return segments
        .where(
          (segment) =>
              segment.endTime > startTime && segment.startTime < endTime,
        )
        .toList();
  }

  Map<String, dynamic> toMap() {
    return {
      'videoId': videoId,
      'language': language,
      'segments': segments.map((s) => s.toMap()).toList(),
      'isAutoGenerated': isAutoGenerated,
      'createdAt': createdAt.toIso8601String(),
    };
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is VideoTranscript &&
          runtimeType == other.runtimeType &&
          videoId == other.videoId &&
          language == other.language;

  @override
  int get hashCode => videoId.hashCode ^ language.hashCode;
}
