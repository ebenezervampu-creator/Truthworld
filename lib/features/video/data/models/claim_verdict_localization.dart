/// Zero-cost, on-device localization catalog for epistemic fact-check verdicts,
/// categories, and takeaways across TruthWorld's supported primary languages.
class ClaimVerdictLocalization {
  ClaimVerdictLocalization._();

  static String _resolveCode(String? raw) {
    if (raw == null || raw.trim().isEmpty) {
      if (UserLanguagesService.isRegistered) {
        return UserLanguagesService.to.primaryLanguageCode;
      }
      return 'en';
    }
    return UserLanguagesService.normalizeCode(raw);
  }

  /// Localizes the canonical verdict badge label (e.g. 'VERIFIED TRUE', 'FALSE CLAIM')
  static String localizeLabel(ClaimVerdictType type, String fallbackLabel, [String? langCode]) {
    final code = _resolveCode(langCode);
    final map = _verdictLabels[type];
    if (map != null && map.containsKey(code)) {
      return map[code]!;
    }
    return fallbackLabel;
  }

  /// Localizes the verdict category (e.g. 'Verified', 'Caution', 'False', 'Contextual')
  static String localizeCategory(String category, [String? langCode]) {
    final code = _resolveCode(langCode);
    final clean = category.trim();
    final map = _categoryLabels[clean.toLowerCase()];
    if (map != null && map.containsKey(code)) {
      return map[code]!;
    }
    return clean;
  }

  /// Localizes the standard summary takeaway explanation
  static String localizeTakeaway(ClaimVerdictType type, String fallbackTakeaway, [String? langCode]) {
    final code = _resolveCode(langCode);
    final map = _takeawaySummaries[type];
    if (map != null && map.containsKey(code)) {
      return map[code]!;
    }
    return fallbackTakeaway;
  }

  /// Localizes short micro takeaways
  static String localizeMicroTakeaway(ClaimVerdictType type, String fallbackMicro, [String? langCode]) {
    final code = _resolveCode(langCode);
    final map = _microTakeaways[type];
    if (map != null && map.containsKey(code)) {
      return map[code]!;
    }
    return fallbackMicro;
  }

